async (page) => {
  const home = 'http://127.0.0.1:8970', blog = 'http://127.0.0.1:8971';
  await page.context().addCookies([{ name: 'p34_routes', value: '1.0.1.0.0.0.0', url: home }]);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(home + '/?paper=0617');
  await page.getByRole('button', { name: '扶住它', exact: true }).waitFor();
  await page.evaluate(() => { window.p34OriginalEntries = [...document.querySelectorAll('.entries > .entry')]; window.p34OriginalTitle = document.querySelector('.title-text'); });
  await page.getByRole('link', { name: /扶住正在掉下来的/ }).click();
  await page.getByRole('button', { name: '你刚才在做什么？', exact: true }).click();
  await page.getByRole('button', { name: '玩玩看', exact: true }).click();
  const ready = () => page.waitForFunction(() => document.querySelector('[data-do=fire]')?.textContent === '发射' && !document.querySelector('[data-do=fire]').disabled);
  const win = () => page.waitForFunction(() => !document.querySelector('[data-do=next]').hidden, null, { timeout: 18000 });
  const center = async locator => { const r = await locator.boundingBox(); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; };
  const moveRail = async (index, target) => {
    const p = await center(page.getByRole('button', { name: new RegExp(`反射横条${index}`) }));
    await page.mouse.move(p.x, p.y); await page.mouse.down(); await page.mouse.move(target.x ?? p.x, target.y ?? p.y, { steps: 15 }); await page.mouse.up();
  };
  const tilt = value => page.locator('.p34-turn input').fill(String(value));
  await ready(); await tilt(-45);
  const p = await center(page.locator('.p34-launch'));
  await page.mouse.move(p.x, p.y); await page.mouse.down(); await page.mouse.move(p.x, p.y - 160, { steps: 12 }); await page.mouse.up();
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await page.getByRole('button', { name: '继续', exact: true }).click(); await win();
  await page.getByRole('button', { name: '下一条路', exact: true }).click(); await ready();
  await moveRail(1, { y: (await center(page.locator('[data-piece=in]'))).y }); await tilt(-45);
  await page.getByRole('button', { name: '发射', exact: true }).click(); await win();
  await page.getByRole('button', { name: '下一条路', exact: true }).click(); await ready();
  await tilt(-45);
  await moveRail(2, { x: (await center(page.locator('[data-piece=goal]'))).x, y: (await center(page.locator('[data-piece=out]'))).y }); await tilt(-45);
  await page.getByRole('button', { name: '发射', exact: true }).click(); await win();
  await page.getByRole('button', { name: '装上试试', exact: true }).click();
  if (!await page.evaluate(() => document.cookie.includes('p34_routes=1.1.2.7.'))) throw new Error('Update lost first-edition progress');
  await page.getByRole('button', { name: '再绕一圈', exact: true }).click(); await ready();
  await tilt(-45); await page.getByRole('button', { name: '发射', exact: true }).click(); await win();
  await page.getByRole('button', { name: '下一条路', exact: true }).click(); await ready();
  await moveRail(1, { y: (await center(page.locator('[data-piece=in]'))).y }); await tilt(-45);
  await page.getByRole('button', { name: '发射', exact: true }).click();
  await page.getByRole('button', { name: '从链接再发射', exact: true }).waitFor({ timeout: 10000 });
  await page.getByRole('button', { name: '从链接再发射', exact: true }).click(); await win();
  await page.getByRole('button', { name: '收起网页', exact: true }).click();
  await page.waitForFunction(() => !document.documentElement.classList.contains('p34-route-playing'));
  if (!await page.evaluate(() => window.p34OriginalEntries.every((el, i) => el === document.querySelectorAll('.entries > .entry')[i]))) throw new Error('Navigation was rebuilt');
  await page.getByRole('button', { name: '你在吗？', exact: true }).click();
  await page.getByRole('button', { name: '把网页还回去吧', exact: true }).click();
  await page.waitForFunction(() => !document.documentElement.classList.contains('p34-native'));
  if (!await page.evaluate(() => document.querySelector('.title-text') === window.p34OriginalTitle && document.querySelector('.title-text').textContent === 'Amiya_desi')) throw new Error('Heading not restored');
  await page.locator('#services-open').click();
  await page.waitForFunction(() => !document.querySelector('#services-note').hidden);
  await page.locator('#services-close').click();

  await page.goto(blog + '/?paper=0617');
  await page.getByRole('button', { name: '我也在这儿看。', exact: true }).waitFor();
  if (await page.locator('.post-row').count() < 1) throw new Error('Real blog articles missing');
  await page.getByRole('link', { name: '博客风格转变记录', exact: true }).click();
  await page.getByRole('button', { name: '旁边有个圈', exact: true }).waitFor();
  await page.evaluate(() => { window.p34Paragraphs = [...document.querySelectorAll('#post-container p')].filter(el => !el.closest('.p34-margin')).map(el => [el, el.textContent]); });
  await page.getByRole('button', { name: '旁边有个圈', exact: true }).click();
  await page.getByRole('button', { name: '这里有个读到一半的人。', exact: true }).click();
  await page.getByRole('button', { name: '请你把原来的页面还给我', exact: true }).click();
  if (!await page.evaluate(() => window.p34Paragraphs.every(([el, text]) => el.isConnected && el.textContent === text))) throw new Error('Article text or nodes changed');
  if (await page.locator('.p34-margin').count()) throw new Error('Margin survived return');
  await page.goto(blog + '/notes/link-brake/?paper=0617');
  await page.waitForFunction(() => document.documentElement.classList.contains('p34-reading'));
  await page.getByRole('link', { name: '沿着旧链接回去', exact: true }).click(); await ready();
  await page.getByText('借道 / 连续版', { exact: true }).waitFor();
  if (!await page.evaluate(() => document.cookie.includes('p34_routes=1.1.2.7.3.1.'))) throw new Error('Cross-site archive or progress missing');
  return { firstEdition: '3 routes', update: 'held and relaunched', normalDOM: 'same nodes restored', blog: 'original article preserved', archive: 'shared progress retained' };
}
