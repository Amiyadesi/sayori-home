import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { packageJourney } from './package-p34-preview.mjs';

test('review package keeps the journey on one origin without changing source or copying Blog services',()=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'p34-preview-'));
  const home=path.join(root,'home'),blog=path.join(root,'blog'),out=path.join(root,'out');
  fs.mkdirSync(home);fs.mkdirSync(path.join(blog,'notes/long-way'),{recursive:true});
  const source=`const blog='https://blog.sayori.org/?paper=0617';const index=post ? post.href : '/?paper=0617';const nav='<a href="/?paper=0617">目录</a>';if (ownNote) { cleanup(); location.assign('/'); return; }`;
  fs.writeFileSync(path.join(home,'p34-space.js'),source);
  const desk='initDesk(); runWhenIdle(loadGuestbookNotes, 3000);';
  fs.writeFileSync(path.join(home,'script.notebook.js'),desk);
  fs.writeFileSync(path.join(home,'index.html'),'<a href="/?paper=0617">入口</a><script defer src="/analytics.notebook.js"></script>');
  fs.writeFileSync(path.join(home,'_headers'),'/*\n  X-Content-Type-Options: nosniff\n');
  fs.writeFileSync(path.join(blog,'her-space.json'),JSON.stringify([{slug:'long-way'}]));
  for(const name of ['paper-blog.js','p34-reading.js','p34-reading.css'])fs.writeFileSync(path.join(blog,name),'');
  fs.writeFileSync(path.join(blog,'notes/long-way/index.html'),'<article data-p34-native-post="long-way"><div class="space-native-prose"><a href="https://sayori.org/?paper=0617&amp;room=archive">试稿</a></div></article>');
  fs.writeFileSync(path.join(blog,'_worker.js'),'must not ship');
  assert.deepEqual(packageJourney(home,blog,out),{notes:1});
  const emitted=fs.readFileSync(path.join(out,'p34-space.js'),'utf8');
  assert.ok(emitted.includes("const blog='/writing/?paper=0617'"));
  assert.ok(emitted.includes("post ? post.href : '/writing/?paper=0617'"));
  assert.match(emitted,/href="\/writing\/\?paper=0617"/);
  assert.equal(fs.readFileSync(path.join(home,'p34-space.js'),'utf8'),source);
  assert.equal(fs.readFileSync(path.join(home,'script.notebook.js'),'utf8'),desk);
  assert.equal(fs.readFileSync(path.join(out,'script.notebook.js'),'utf8'),'initDesk(); ');
  assert.ok(emitted.includes("if (site === 'blog') { cleanup(); location.assign('https://blog.sayori.org/'); return; }"));
  assert.doesNotMatch(fs.readFileSync(path.join(out,'index.html'),'utf8'),/analytics/);
  const note=fs.readFileSync(path.join(out,'notes/long-way/index.html'),'utf8');
  assert.match(note,/<article hidden\b/);
  assert.match(note,/background:#08090a/);
  assert.match(note,/href="\/\?paper=0617&amp;room=archive"/);
  assert.ok(fs.existsSync(path.join(out,'writing/index.html')));
  assert.equal(fs.existsSync(path.join(out,'_worker.js')),false);
  assert.throws(()=>packageJourney(home,home,path.join(root,'bad')),/ENOENT/);
});
